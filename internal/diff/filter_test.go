func TestMatcher(t *testing.T) {
	m := NewMatcher(DefaultExcludes...)
	m.Add("# comment", "", "secrets/", "/build", "docs/**/*.draft.md", "!keep.lock", "tmp?.txt", "data[0-9].csv", "\\#hash")
	tests := []struct {
		path string
		want bool
	}{
		{"package-lock.json", true},
		{"web/package-lock.json", true},
		{"go.sum", true},
		{"Cargo.lock", true},
		{"keep.lock", false}, // negated
		{"vendor/github.com/x/y.go", true},
		{"src/node_modules/react/index.js", true},
		{"assets/logo.PNG", false}, // case-sensitive like git on Linux
		{"assets/logo.png", true},
		{"dist/app.min.js", true},
		{"api/v1/service.pb.go", true},
		{"main.go", false},
		{"vendor.go", false},              // "vendor/" only matches directories
		{"secrets/prod.yaml", true},       // dir-only pattern
		{"secrets", false},                // a file named secrets is not a dir
		{"build/out.txt", true},           // anchored dir
		{"pkg/build/out.txt", false},      // anchored → only at root
		{"docs/a/b/x.draft.md", true},     // **
		{"docs/x.draft.md", true},         // ** matches zero dirs
		{"tmp1.txt", true}, {"tmp12.txt", false},
		{"data7.csv", true}, {"dataX.csv", false},
		{"#hash", true},
		{"./main.go", false},
	}
	for _, tt := range tests {
		if got := m.Match(tt.path); got != tt.want {
			t.Errorf("Match(%q) = %v, want %v", tt.path, got, tt.want)
		}
	}
}

func TestMatcherNegatedCharClassAndBadPatterns(t *testing.T) {
	m := NewMatcher("file[!a].txt", "/", "!", "x[")
	if !m.Match("fileb.txt") || m.Match("filea.txt") {
		t.Error("negated class")
	}
	if !m.Match("x[") {
		t.Error("unterminated class should match literally")
	}
}

func TestMatcherAddFile(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, ".git-quill-ignore")
	if err := os.WriteFile(p, []byte("*.snap\n!important.snap\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	m := NewMatcher()
	if err := m.AddFile(p); err != nil {
		t.Fatal(err)
	}
	if err := m.AddFile(filepath.Join(dir, "missing")); err != nil {
		t.Fatalf("missing file should be ignored: %v", err)
	}
	if !m.Match("ui/a.snap") || m.Match("important.snap") {
		t.Error("ignore file rules not applied")
	}
	if err := m.AddFile(dir); err == nil {
		t.Error("reading a directory should fail")
	}
}

func TestFilter(t *testing.T) {
	long := "+" + strings.Repeat("x", maxLineLen+1)
	d := sample +
		"diff --git a/yarn.lock b/yarn.lock\n--- a/yarn.lock\n+++ b/yarn.lock\n@@ -1 +1 @@\n-a\n+b\n" +
		"diff --git a/gen.go b/gen.go\n--- a/gen.go\n+++ b/gen.go\n@@ -0,0 +1,2 @@\n+// Code generated by protoc. DO NOT EDIT.\n+package gen\n" +
		"diff --git a/app.js b/app.js\n--- a/app.js\n+++ b/app.js\n@@ -0,0 +1 @@\n" + long + "\n"
	kept, excluded := Filter(Parse(d), NewMatcher(DefaultExcludes...))
	var keptPaths []string
	for _, f := range kept {
		keptPaths = append(keptPaths, f.Path())
	}
	if strings.Join(keptPaths, ",") != "internal/auth/login.go,docs/new file.md,old.txt,b/after.go,ทดสอบ.txt" {
		t.Errorf("kept = %v", keptPaths)
	}
	want := map[string]string{
		"logo.png":  "ignore pattern",
		"yarn.lock": "ignore pattern",
		"gen.go":    "generated",
		"app.js":    "minified (very long lines)",
	}
	if len(excluded) != len(want) {
		t.Fatalf("excluded = %v", excluded)
	}
	for _, e := range excluded {
		if want[e.Path] != e.Reason {
			t.Errorf("%s excluded for %q, want %q", e.Path, e.Reason, want[e.Path])
		}
	}
	if excluded[0].String() != "logo.png (ignore pattern)" {
		t.Errorf("String() = %q", excluded[0])
	}

	// Without a matcher, binaries are still dropped.
	_, ex := Filter(Parse(sample), nil)
	if len(ex) != 1 || ex[0].Reason != "binary" {
		t.Errorf("nil matcher excluded = %v", ex)
	}
}

func TestEstimateAndTruncate(t *testing.T) {
	if got := EstimateTokens("abcdefgh"); got != 2 {
		t.Errorf("ascii estimate = %d", got)
	}
	if got := EstimateTokens("สวัสดี"); got != 6 {
		t.Errorf("thai estimate = %d", got)
	}
	s := strings.Repeat("0123456789abcdef\n", 100) // ~17 bytes/line
	out, cut := Truncate(s, 50)
	if !cut || !strings.Contains(out, "[truncated: ") || EstimateTokens(out) > 70 {
		t.Errorf("truncate: cut=%v tokens=%d", cut, EstimateTokens(out))
	}
	same, cut := Truncate("short", 50)
	if cut || same != "short" {
		t.Error("short input should not be truncated")
	}
}

func TestChunks(t *testing.T) {
	files := Parse(sample)
	all := Chunks(files, 1_000_000)
	if len(all) != 1 || all[0] != sample {
		t.Errorf("large budget should give one chunk, got %d", len(all))
	}
	small := Chunks(files, 60)
	if len(small) < 3 {
		t.Errorf("small budget gave %d chunks", len(small))
	}
	for _, c := range small {
		if EstimateTokens(c) > 80 {
			t.Errorf("chunk over budget (%d tokens):\n%s", EstimateTokens(c), c)
		}
	}
	tiny := Chunks(files[:1], 20)
	if len(tiny) != 1 || !strings.Contains(tiny[0], "[truncated") {
		t.Errorf("oversized file should be one truncated chunk: %q", tiny)
	}
	if Chunks(nil, 10) != nil {
		t.Error("no files → no chunks")
	}
}
